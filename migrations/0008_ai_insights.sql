-- خبيئةُ استبصارات التحليلات.
--
-- ═══ لماذا تُخبَّأ ولا تُحسب عند كل فتحة ═══
--
-- الاستدلال يستغرق ثوانيَ ويُحاسَب عليه بالرموز. وشاشةُ التحليلات تُفتح
-- مراراً في اليوم، وأرقامُها لا تتبدّل بين فتحةٍ وأخرى في الغالب.
-- فتشغيلُه في كل فتحة يدفع ثمناً لنتيجةٍ واحدة مكرّرة.
--
-- والمفتاح بصمةُ الخلاصة لا الوقت: ما دامت الأرقام هي هي فالاستبصار هو
-- هو، ولا معنى لإعادته. وأوّلُ تبدّلٍ في رقمٍ يبدّل البصمة فيُعاد.
CREATE TABLE IF NOT EXISTS ai_insights (
  -- بصمة الخلاصة (SHA-256 مقتطعة). صفٌّ واحد لكل حالةِ أرقام.
  digest_hash TEXT PRIMARY KEY,

  -- الاستبصارات JSON كما ردّها الطراز بعد التنقية.
  payload     TEXT NOT NULL,

  -- الخلاصة نفسها: تُحفظ ليُقرأ ما بُني عليه الاستبصار، فلا يُقرأ رأيٌ
  -- بلا الأرقام التي أنتجته.
  digest      TEXT NOT NULL,

  model       TEXT NOT NULL,
  created_at  INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_ai_insights_created ON ai_insights(created_at DESC);
