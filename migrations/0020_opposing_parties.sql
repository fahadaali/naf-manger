-- الأطرافُ الخصم — وبها يُفحص تعارضُ المصالح.
--
-- ═══ المسألة ═══
--
-- مكتبُ محاماة لا يقبل موكّلاً هو خصمٌ في قضيةٍ قائمةٍ لموكّلٍ آخر، ولا
-- يرفع قضيةً على موكّلٍ عنده. ولم يكن في القضية ما يقول مَن الخصم — فالفحصُ
-- ذاكرةُ من يستقبل الموكّلَ الجديد، وتخونه في المكتب الكبير.
--
-- فـ`opposing_parties`: JSON `[{ "name": "…", "idNumber": "…" }]` — طرفٌ أو
-- أكثر، ورقمُ الهوية أو السجلّ اختياريّ. ويُكتب من نافذة القضية، ويُقرأ من
-- «بيانات المشروع» في بيسكامب تحت عنوان «الخصم» وأخواته.
--
-- وكلُّه `ADD COLUMN` — لا `DROP TABLE`، فلا حذفٌ ضمنيٌّ يُشعل
-- `ON DELETE CASCADE` كما وقع في الهجرة العاشرة.

ALTER TABLE cases ADD COLUMN opposing_parties TEXT NOT NULL DEFAULT '[]';
