-- ما يخصّ العضو في هذه المنصة وحدها.
--
-- الاسم والبريد والدور تكتبها `naf-auth` من رمز المركز عند كل دخول، فلا
-- يُعدَّل شيء منها هنا — يُدهس في الدخول التالي. وهذان العمودان بخلاف
-- ذلك: لا يعرفهما المركز ولا يمسّهما، فهما موضعُ ما تملكه المنصة من
-- ملفّ العضو.

-- مفتاح الصورة في حاوية R2 — لا الصورة نفسها.
--
-- كانت الواجهة تقرأ الملفّ بـ`readAsDataURL` وتحشر النصّ base64 في
-- الصفّ: حتى ٢٫٧ ميغابايت نصّاً للصورة الواحدة، تُنقل مع كل قراءةِ صفّ
-- ومع كل قائمة. والحاوية كانت مربوطةً ومسارُها `‎/api/files‎` جاهزاً
-- وصفرُ نداءات إليه. فالمفتاح هنا، والبايتات هناك.
ALTER TABLE members ADD COLUMN avatar_key TEXT;

-- تفضيلات الإشعارات — JSON، و`NULL` يعني «الافتراض» لا «لا شيء».
--
-- وهي تفضيلاتُ عضوٍ لا إعدادُ منصة، فموضعُها صفُّه لا `system_settings`:
-- ذاك كائنٌ واحد للمنصة كلِّها، ولو وُضعت فيه لدهس كلُّ عضوٍ اختيار من
-- قبله.
ALTER TABLE members ADD COLUMN notification_prefs TEXT;
