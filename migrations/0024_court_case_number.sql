-- رقمُ القضية لدى الجهة المختصة — حقلٌ تفصيليّ، لا مفتاح.
--
-- ═══ المسألة ═══
--
-- كان «رقم القضية» في ملفّ «بيانات المشروع» يُقرأ إلى `cases.case_number` —
-- العمودِ الفريد الذي تُطابَق به القضية. وهو في ملفّات المكتب رقمُ القضية لدى
-- المحكمة أو الشرطة أو النيابة: يتكرّر بين مشاريع، ويغيب في غيرها. فصار تعارضاً
-- على ما ليس مفتاحاً.
--
-- والمفتاحُ الصحيح رقمُ المشروع: **معرّفُه في بيسكامب** — الثابتُ في رابطه. فـ
-- `case_number` لقضيةٍ من بيسكامب صار معرّفَ مشروعها (`basecamp/sync.js`)، ورقمُ
-- الجهة هنا، **بلا تفرّد**، ومعه الجهةُ نفسُها.
--
-- والقضايا المستوردة قبل هذا لا تُصحَّح هنا: تُعاد من «الربط ببيسكامب ← إعادة
-- الاستيراد» بيد المسؤول، بعد نسخةٍ احتياطية ومعاينة.
--
-- وكلُّه `ADD COLUMN` — لا `DROP TABLE`.

ALTER TABLE cases ADD COLUMN authority TEXT;
ALTER TABLE cases ADD COLUMN court_case_number TEXT;
CREATE INDEX IF NOT EXISTS idx_cases_court_number ON cases(court_case_number);

