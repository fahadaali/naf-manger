-- ملفُّ بيسكامب صار «بيانات المشروع»، وفيه ملاحظاتٌ لم يكن يحملها.
--
-- ═══ ملاحظاتُ القضية ═══
--
-- «بيانات المشروع» يحمل الآن ملاحظاتٍ مكتوبةً بخطّ من يتابع الملفّ. وكانت
-- تصل القارئَ ثم لا تجد عموداً تُكتب فيه، فتُطرح صامتة. و`summary` لا
-- تصلح لها: الملخّص موضوعُ القضية، والملاحظةُ حاشيةٌ عليه — وخلطُهما
-- يجعل تعديلَ إحداهما يمحو الأخرى.
--
-- وللعميل عمودُ `notes` منذ الهجرة الثانية، فلا يُضاف له شيء.
--
-- ═══ واسمُ الملفّ يُحفظ كما هو عندهم ═══
--
-- المكتبُ يعيد تسمية الملفّ (وقد فعل مرّة)، والمسحُ يبحث عن عنوانٍ بعينه.
-- فيُحفظ العنوانُ الذي وُجد فعلاً، لتقول الشاشةُ «الملفّ هنا اسمه كذا»
-- بدل أن يظهر المشروعُ بلا ملفّ ولا سبب.
--
-- وكلُّه `ADD COLUMN` — لا `DROP TABLE`، فلا حذفٌ ضمنيٌّ يُشعل
-- `ON DELETE CASCADE` كما وقع في الهجرة العاشرة.

ALTER TABLE cases ADD COLUMN notes TEXT NOT NULL DEFAULT '';

ALTER TABLE basecamp_projects ADD COLUMN doc_title TEXT;
