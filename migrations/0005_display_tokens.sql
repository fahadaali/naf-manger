-- رموز شاشات العرض.
--
-- ═══ لماذا وُجد هذا الجدول ═══
--
-- كانت شاشة «عرض لوحة التحكم» تنسخ `origin + pathname` — أي عنوان المنصة
-- نفسه — وتَعِد بعرضه على شاشات المكتب. وهو خلف الحارس: أيُّ شاشةٍ تفتحه
-- تُحوَّل إلى المركز وتطلب دخولاً. فالميزة موعودةٌ ولا يمكن أن تعمل.
--
-- وشاشةُ عرضٍ معلَّقة في ممرّ لا تسجّل دخولاً ولا تُحرس بكوكي. فالوصول
-- برمزٍ في الرابط، وهذا ما يوجب الحدود الأربعة أدناه.

CREATE TABLE IF NOT EXISTS display_tokens (
  -- الرمز نفسه: ٣٢ بايتاً عشوائية بترميز base64url. وهو المفتاح فيمنع
  -- التصادم بنيةً، ويُبحث به مباشرةً بلا مسحٍ للجدول.
  token       TEXT PRIMARY KEY,

  -- اسمٌ يقوله المسؤول ليعرف أيَّ شاشةٍ يُبطل: «شاشة الاستقبال».
  label       TEXT NOT NULL DEFAULT '',

  created_by  TEXT NOT NULL,
  created_at  INTEGER NOT NULL,

  -- آخر قراءةٍ بهذا الرمز. يقول للمسؤول أيُّ رمزٍ حيٌّ وأيُّه منسيّ —
  -- ورمزٌ منسيٌّ حيٌّ هو الخطر لا الرمز المستعمل.
  last_seen_at INTEGER,

  -- الإبطال حذفُ صفٍّ: لا عمود `is_active` يُنسى فحصُه في مسارٍ جديد.
  -- والمسار العامّ يقرأ بالمفتاح، فغيابُ الصفّ هو الرفض نفسه.
  CHECK (length(token) >= 32)
);

CREATE INDEX IF NOT EXISTS idx_display_tokens_created ON display_tokens(created_at DESC);

-- ═══ ما لا يُقرأ بهذا الرمز ═══
--
-- المسار العامّ يردّ ما يردّه `‎/api/stats‎` وحده: أعداداً مجمَّعة — عدد
-- العملاء، وتوزيعُهم على الأنواع، وحالاتُ القضايا، ومعدّلُ الربح. ولا
-- اسمَ عميلٍ ولا رقمَ قضية ولا مبلغ.
--
-- وذلك شرطٌ لا تحسين: الرابط يعيش في شاشةٍ يراها كلُّ من يمرّ، وقد يُصوَّر
-- أو يُنسخ. فما خلفه يجب أن يحتمل ذلك.
