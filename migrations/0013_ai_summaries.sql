-- الملخّصُ الآليّ — حقلٌ مستقلٌّ عن الملاحظات.
--
-- ═══ لماذا لا يُكتب في `notes` ═══
--
-- `notes` يكتبها المحامي، ويأتي فيها ما في «بيانات المشروع». ونصٌّ صاغه
-- طرازٌ لو دخلها لاختلط بما كتبه إنسان — فيُقرأ بعد شهرٍ كأنّ محامياً
-- كتبه، ويدخل الدمجَ الثلاثي فيبدو أنّ «يداً مسّت الحقل» في كل مزامنة.
--
-- فحقلٌ باسمه، يُعرض تحت الملاحظات مسمّىً «ملخّصٌ آليّ». ومن أراد نقله
-- إليها نسخه بيده — وذلك قرارُ إنسانٍ لا أثرٌ جانبيّ لجدولة.
--
-- ═══ والبصمةُ تمنع إعادة الاستدلال ═══
--
-- المزامنة تعمل كلَّ ساعة. وتلخيصُ كلِّ قضيةٍ في كل دورة يدفع ثمناً
-- لنتيجةٍ واحدة مكرّرة، ويبلغ حدَّ النداءات بلا طائل. فتُحفظ بصمةُ النصّ
-- الذي لُخِّص: ما دام هو هو فالملخّصُ هو هو، ولا يُعاد.
--
-- وكلُّه `ADD COLUMN` — لا `DROP TABLE`، فلا حذفٌ ضمنيٌّ يُشعل
-- `ON DELETE CASCADE` كما وقع في الهجرة العاشرة.

ALTER TABLE cases ADD COLUMN ai_summary      TEXT;
ALTER TABLE cases ADD COLUMN ai_summary_hash TEXT;
ALTER TABLE cases ADD COLUMN ai_summary_at   INTEGER;   -- ثوانٍ

-- وللعميل ملخّصُ قضاياه مجتمعةً: «ثلاثُ قضايا تجارية، اثنتان مكتملتان».
-- يُبنى من صفوف قضاياه في المنصة لا من ملفٍّ واحد، فيتبدّل بتبدّلها.
ALTER TABLE clients ADD COLUMN ai_summary      TEXT;
ALTER TABLE clients ADD COLUMN ai_summary_hash TEXT;
ALTER TABLE clients ADD COLUMN ai_summary_at   INTEGER;
