-- اسمُ الملفّ الجاري يبلغ العناوينَ المحفوظة في القاعدة.
--
-- ═══ العلّة ═══
--
-- الملفُّ الذي يفرّق مشروعَ العميل من الداخلي صار «بيانات المشروع» بعد أن
-- كان «ملخص القضية». والاسمُ الجاري أُدخل في افتراض الشيفرة
-- (`DEFAULT_DOC_TITLES`) — وذلك يكفي مكتباً لم يضبط عناوينَه بيده.
--
-- ولا يكفي من ضبطها: `readDocTitles` تقرأ ما في `system_settings` وتردّه
-- كما هو، ولا تنظر إلى الافتراض إلا حين لا تجد صفّاً. فمكتبٌ حفظ
-- «ملخص القضية» قبل إعادة التسمية يبقى يبحث عن اسمٍ لم يعد موجوداً:
-- المشاريعُ الجديدة تظهر بلا ملفّ، وتُصنَّف `internal`، ولا يقول أحدٌ لِمَ.
--
-- والقديمةُ منها ينجّيها معرّفُ الملفّ — `findProjectDocument` تعرفه من
-- مسحٍ سابق وإن تبدّل عنوانُه. أمّا مشروعٌ لم يُمسح قطّ فلا معرّفَ له،
-- فيسقط.
--
-- ═══ والعلاجُ إضافةٌ لا استبدال ═══
--
-- يُدخَل الاسمُ الجاري أوّلَ القائمة، ويبقى ما بعده على حاله: مشاريعُ
-- سنينَ ماضية لم يُعَد تسميةُ ملفّاتها، وحذفُ «ملخص القضية» يُطفئ نصفَ
-- الحساب. والأوّلُ هو الجاري — والشاشة تقرؤها بهذا الترتيب.
--
-- وما ضُبط بيدٍ لا يُدهس: العناوينُ الأخرى تُنقل كما كُتبت، ومن أراد
-- حذفَ الاسم الجاري بعد هذه الهجرة حذفه من الشاشة ولا تعود تكتبه.
--
-- ═══ وهي آمنةٌ للتكرار ═══
--
-- `NOT EXISTS` يجعل تشغيلَها مرّتين تشغيلاً واحداً. وصفٌّ لا يحمل مصفوفةَ
-- JSON صحيحة لا يُمسّ — `json_valid` و`json_type` يحرسانه، و`readDocTitles`
-- تردّ التالفَ إلى الافتراض أصلاً. ولا صفَّ يُنشأ لمن لم يضبط شيئاً:
-- غيابُ الصفّ هو ما يجعله يقرأ الافتراض، وهو الجاري.

UPDATE system_settings
SET value = (
      SELECT json_group_array(merged.title)
      FROM (
        SELECT 'بيانات المشروع' AS title, 0 AS ordinal
        UNION ALL
        SELECT stored.value, 1
        FROM json_each(system_settings.value) AS stored
        WHERE stored.value <> 'بيانات المشروع'
        ORDER BY ordinal
      ) AS merged
    ),
    updated_at = CAST(strftime('%s', 'now') AS INTEGER)
WHERE key = 'basecamp_doc_titles'
  AND json_valid(value)
  AND json_type(value) = 'array'
  AND NOT EXISTS (
        SELECT 1
        FROM json_each(system_settings.value) AS stored
        WHERE stored.value = 'بيانات المشروع'
      );
