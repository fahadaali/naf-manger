/* ============================================================
   تصنيف رسالة الحالة — موضعٌ واحد بدل تسعة.

   ═══ العطل الذي أوجب هذا الملفّ ═══

   كانت تسع شاشات تسأل ‎saveMessage.includes('نجاح')‎ لتقرّر أخضر أم
   أحمر. ثم وُحّدت رسائل النجاح على صيغة §٤ المسجَّلة — «تم + المصدر» —
   فسقطت كلمة «بنجاح» من كلّ رسالة، وصار الشرط لا يتحقّق أبداً: كل
   رسالة نجاح تُعرض حمراء.

   وهو عطبٌ صامت: لا يسقط البناء، ولا يظهر في السجلّ، ولا يراه إلا من
   حفظ شيئاً فقيل له إنه فشل.

   ═══ لماذا لا يُستنبَط من نصّ ثانٍ ═══

   استبدالُ «نجاح» بـ«تم» يعيد العطب نفسه بعد تعديلٍ آخر. لكن الصيغة
   هنا ليست كلمةً منتقاة: §٤ تنصّ على أن رسالة النجاح **تُبنى** على
   «تم + المصدر» — «تم الحفظ» و«تمت إضافة المستخدم» — وهي قاعدة النظام
   لا اصطلاح شاشة. فقراءتها قراءةٌ للقاعدة، وموضعُها واحدٌ يُعدَّل مرّة.

   والأصحّ منه حالةٌ صريحة تُضبط مع الرسالة. وهي التالية إن تعدّدت
   الحالات على أكثر من اثنتين — يومَها لن يكفي هذا.
   ============================================================ */

/** صيغة النجاح المسجَّلة: «تم» أو «تمت» ثم المصدر. */
const SUCCESS = /^تمّ?ت?\s/;

export type MessageTone = 'success' | 'destructive';

/** نبرة الرسالة: نجاحٌ أم خطأ. الفارغة تُعدّ خطأً ولا تُعرض أصلاً. */
export function messageTone(message: string): MessageTone {
  return SUCCESS.test(message.trim()) ? 'success' : 'destructive';
}
